import '../src/data/frameworks/nist80053/objectivesNode';
import { nist80053ObjectiveTemplate } from '../src/data/frameworks/nist80053/objectives';
import { getAssessmentObjectivesForControl } from '../src/data/frameworks/assessmentObjectives';
import file from '../src/data/frameworks/nist80053/objectives.generated.json';

/** SP 800-53A objective letter scheme: letters are normalised, repeats get x2/x3 in data order, and the stored id is `${control}[${letter}]`. Pins the scheme so a regeneration that re-keys anything fails loudly. */
let passed = 0;
let total = 0;
function assert(condition: boolean, name: string, detail?: unknown) {
  total++;
  if (condition) {
    passed++;
    console.log(`  ✓ PASS: ${name}`);
  } else {
    console.error(`  ✗ FAIL: ${name}${detail !== undefined ? ` -> ${JSON.stringify(detail)}` : ''}`);
  }
}
const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);
const letters = (id: string) => nist80053ObjectiveTemplate(id)?.objectives.map((o) => o.letter);
const textOf = (id: string, letter: string) => nist80053ObjectiveTemplate(id)?.objectives.find((o) => o.letter === letter)?.text ?? '';

console.log('--- Letter shapes ---');
const ac2 = ['a01', 'a02', 'b', 'c', 'd01', 'd02', 'd0301', 'd0302', 'e', 'f01', 'f02', 'f03', 'f04', 'f05', 'g', 'h01', 'h02', 'h03', 'i01', 'i02', 'i03', 'j', 'k01', 'k02', 'l01', 'l02'];
assert(same(letters('AC-2'), ac2), 'L71-1: AC-2 letters (26)', letters('AC-2'));
assert(same(letters('AC-3(3)'), ['01', '02', 'a01', 'a02', 'b01', 'b02', 'b03', 'b04', 'b05', 'c']), 'L71-2: AC-3(3) letters', letters('AC-3(3)'));

console.log('\n--- Duplicate letters get x2, x3 in data order ---');
assert(same(letters('CA-7(4)'), ['a', 'ax2', 'b', 'c']), 'L71-3: CA-7(4) letters', letters('CA-7(4)'));
assert(textOf('CA-7(4)', 'a').startsWith('risk monitoring is an integral part of the continuous monitoring strategy'), 'L71-3: CA-7(4) a carries the risk monitoring text', textOf('CA-7(4)', 'a').slice(0, 80));
assert(textOf('CA-7(4)', 'ax2').startsWith('effectiveness monitoring is included in risk monitoring'), 'L71-3: CA-7(4) ax2 carries the effectiveness monitoring text', textOf('CA-7(4)', 'ax2').slice(0, 80));
assert(same(letters('PM-24'), ['a', 'ax2', 'b']), 'L71-4: PM-24 letters', letters('PM-24'));
assert(textOf('PM-24', 'a').startsWith('a Data Integrity Board is established'), 'L71-4: PM-24 a text', textOf('PM-24', 'a').slice(0, 80));
assert(textOf('PM-24', 'ax2').startsWith('the Data Integrity Board reviews proposals'), 'L71-4: PM-24 ax2 text', textOf('PM-24', 'ax2').slice(0, 80));
assert(same(letters('PM-31'), ['a', 'ax2', 'b01', 'b02', 'c', 'd01', 'd02', 'e01', 'e02', 'f01', 'f02']), 'L71-5: PM-31 letters', letters('PM-31'));
assert(textOf('PM-31', 'a').startsWith('an organization-wide continuous monitoring strategy is developed'), 'L71-5: PM-31 a text', textOf('PM-31', 'a').slice(0, 80));
assert(textOf('PM-31', 'ax2').startsWith('continuous monitoring programs are implemented that include establishing'), 'L71-5: PM-31 ax2 text', textOf('PM-31', 'ax2').slice(0, 80));

console.log('\n--- Stored id shape ---');
assert(same(getAssessmentObjectivesForControl('CA-7(4)').map((o) => o.id), ['CA-7(4)[a]', 'CA-7(4)[ax2]', 'CA-7(4)[b]', 'CA-7(4)[c]']), 'L71-6: CA-7(4) stored ids', getAssessmentObjectivesForControl('CA-7(4)').map((o) => o.id));

console.log('\n--- Whole catalog ---');
const keys = Object.keys((file as { objectives: Record<string, unknown> }).objectives);
const bad: string[] = [];
const xControls: Record<string, string[]> = {};
for (const key of keys) {
  const l = letters(key) ?? [];
  if (new Set(l).size !== l.length || !l.every((x) => /^[a-z0-9]+$/.test(x))) bad.push(key);
  if (l.some((x) => /x\d+$/.test(x))) xControls[key] = l;
}
assert(keys.length > 0 && bad.length === 0, 'L71-7: every control has unique [a-z0-9]+ letters', bad.slice(0, 10));
const xIds = Object.keys(xControls).sort();
for (const id of ['CA-7(4)', 'CM-7(7)', 'PE-11(2)', 'PM-24', 'PM-31']) {
  assert(xIds.includes(id), `L71-8: ${id} has an x-suffixed letter`);
}

console.log('\n--- Exact x-suffixed set ---');
// Generated by a run: a regeneration that re-keys any control changes these lists.
const EXPECTED_X_CONTROLS = ['CA-7(4)', 'CM-7(7)', 'PE-11(2)', 'PM-24', 'PM-31', 'SI-2(7)'];
const EXPECTED_X_LETTERS: Record<string, string[]> = {
  'CA-7(4)': ['a', 'ax2', 'b', 'c'],
  'CM-7(7)': ['a', 'ax2', 'b'],
  'PE-11(2)': ['a', 'ax2', 'b', 'c'],
  'PM-24': ['a', 'ax2', 'b'],
  'PM-31': ['a', 'ax2', 'b01', 'b02', 'c', 'd01', 'd02', 'e01', 'e02', 'f01', 'f02'],
  'SI-2(7)': ['a', 'ax2', 'b', 'ax3', 'ax4'],
};
assert(same(xIds, EXPECTED_X_CONTROLS), 'L71-9: exact sorted list of x-suffixed controls', xIds);
for (const id of EXPECTED_X_CONTROLS) {
  assert(same(xControls[id], EXPECTED_X_LETTERS[id]), `L71-10: ${id} exact letter list`, xControls[id]);
}

console.log(`\n📊 TEST RESULTS: ${passed} / ${total}`);
if (passed !== total) process.exitCode = 1;
